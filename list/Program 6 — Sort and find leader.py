# Create the new Justice League team
justice_league = [
    "Cyborg",
    "Shazam",
    "Hawkgirl",
    "Martian Manhunter",
    "Green Arrow"
]

# Sort the list alphabetically
justice_league.sort()

# Display the sorted list
print("Alphabetically sorted Justice League:")
print(justice_league)

# The hero at index 0 becomes the new leader
print("New leader:", justice_league[0])